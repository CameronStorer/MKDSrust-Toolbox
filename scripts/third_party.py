"""Writes docs/THIRD_PARTY.md: every Rust crate and npm package compiled into the Toolbox, with its license.

Run from the repository root: `python scripts/third_party.py`. Needs `cargo` and an installed `app/node_modules`.
"""
import json
import os
import subprocess

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
meta = json.loads(
    subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--offline", "--filter-platform", "x86_64-pc-windows-msvc"],
        cwd=root,
    )
)
workspace = set(meta["workspace_members"])
by_id = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
# Shipped dependencies only: follow normal edges, skip dev- and build-only ones.
seen, todo = set(), list(workspace)
while todo:
    i = todo.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] is None for k in d["dep_kinds"]):
            todo.append(d["pkg"])
crates = sorted((by_id[i] for i in seen - workspace), key=lambda p: (p["name"], p["version"]))

app = os.path.join(root, "app")
pkg = json.load(open(os.path.join(app, "package.json"), encoding="utf-8"))
npm, todo = {}, list(pkg.get("dependencies", {}))
while todo:
    name = todo.pop()
    if name in npm:
        continue
    path = os.path.join(app, "node_modules", name, "package.json")
    if not os.path.exists(path):
        continue
    p = json.load(open(path, encoding="utf-8"))
    lic = p.get("license") or (p.get("licenses") or [{}])[0].get("type", "")
    if isinstance(lic, dict):
        lic = lic.get("type", "")
    repo = p.get("repository")
    repo = repo.get("url", "") if isinstance(repo, dict) else (repo or "")
    npm[name] = (p.get("version", ""), lic, p.get("homepage") or repo)
    todo += list(p.get("dependencies", {}))


def link(url):
    url = (url or "").replace("git+", "").replace("git://", "https://").removesuffix(".git").split("#")[0]
    if url.startswith("github:"):
        url = "https://github.com/" + url[7:]
    return url if url.startswith("http") else ""


out = [
    "# Third-party software",
    "",
    "Generated by `scripts/third_party.py`. These are the libraries compiled into the Toolbox app and CLI, with the",
    "license each one declares. Projects we studied for formats and workflows, but did not ship, are credited in",
    "`CREDITS.md`.",
    "",
    f"## Rust crates ({len(crates)})",
    "",
    "| Crate | Version | License |",
    "|---|---|---|",
]
for p in crates:
    url = link(p.get("repository") or p.get("homepage"))
    name = f"[{p['name']}]({url})" if url else p["name"]
    out.append(f"| {name} | {p['version']} | {p.get('license') or 'see crate'} |")
out += ["", f"## JavaScript packages ({len(npm)})", "", "| Package | Version | License |", "|---|---|---|"]
for name in sorted(npm):
    version, lic, url = npm[name]
    url = link(url)
    out.append(f"| {f'[{name}]({url})' if url else name} | {version} | {lic or 'see package'} |")
with open(os.path.join(root, "docs", "THIRD_PARTY.md"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
licenses = {}
for p in crates:
    licenses[p.get("license")] = licenses.get(p.get("license"), 0) + 1
for v in npm.values():
    licenses[v[1]] = licenses.get(v[1], 0) + 1
print(len(crates), "crates,", len(npm), "npm packages")
for k, n in sorted(licenses.items(), key=lambda x: -x[1]):
    print(f"{n:4} {k}")
